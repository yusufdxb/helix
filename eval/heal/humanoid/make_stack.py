#!/usr/bin/env python3
"""Write a real ROS 2 humanoid stack for the healer to supervise.

Everything here is stock ROS 2 Humble software, not a helix_demo stage:
  controller_manager   ros2_control_node with mock_components/GenericSystem hardware for a 23-joint
                       humanoid (Unitree G1 joint layout), a joint_state_broadcaster and a
                       forward_command_controller. Publishes /joint_states at the update rate.
  rsp                  robot_state_publisher. Consumes /joint_states, publishes /tf.
  camera               image_tools/cam2image in burger mode, 30 Hz on /image.
  camera_backup        a second cam2image at 15 Hz, started only as a fallback.
The controllers are loaded by the stock spawner, run as a `then` helper after every
(re)start of controller_manager, which is how a launch file would do it.

Usage: make_stack.py OUT_DIR [--rate 250]. Writes g1.urdf, controllers.yaml, rsp.yaml and
humanoid.spec with absolute paths into OUT_DIR.
"""
import argparse
import os

SIDE_LEG = ["hip_pitch", "hip_roll", "hip_yaw", "knee", "ankle_pitch", "ankle_roll"]
SIDE_ARM = ["shoulder_pitch", "shoulder_roll", "shoulder_yaw", "elbow", "wrist_roll"]
AXIS = {"pitch": "0 1 0", "roll": "1 0 0", "yaw": "0 0 1", "knee": "0 1 0", "elbow": "0 1 0"}


def joints():
    out = []
    for s in ("left", "right"):
        out += [f"{s}_{j}_joint" for j in SIDE_LEG]
    out.append("waist_yaw_joint")
    for s in ("left", "right"):
        out += [f"{s}_{j}_joint" for j in SIDE_ARM]
    return out


def axis(j):
    for k, v in AXIS.items():
        if k in j:
            return v
    return "0 0 1"


def urdf(rate):
    links = ["pelvis", "torso_link"]
    js = []

    def chain(parent, names, origin):
        p = parent
        for i, n in enumerate(names):
            child = n.replace("_joint", "_link")
            links.append(child)
            xyz = origin if i == 0 else "0 0 -0.08"
            js.append((n, p, child, xyz))
            p = child

    chain("pelvis", [f"left_{j}_joint" for j in SIDE_LEG], "0 0.09 -0.05")
    chain("pelvis", [f"right_{j}_joint" for j in SIDE_LEG], "0 -0.09 -0.05")
    js.append(("waist_yaw_joint", "pelvis", "torso_link", "0 0 0.1"))
    chain("torso_link", [f"left_{j}_joint" for j in SIDE_ARM], "0 0.15 0.3")
    chain("torso_link", [f"right_{j}_joint" for j in SIDE_ARM], "0 -0.15 0.3")
    s = ['<?xml version="1.0"?>', '<robot name="g1_like">']
    s += [f'  <link name="{name}"/>' for name in links]
    for n, p, c, xyz in js:
        s.append(f'  <joint name="{n}" type="revolute"><parent link="{p}"/><child link="{c}"/>'
                 f'<origin xyz="{xyz}" rpy="0 0 0"/><axis xyz="{axis(n)}"/>'
                 f'<limit lower="-2.5" upper="2.5" effort="100" velocity="20"/></joint>')
    s.append('  <ros2_control name="g1_mock" type="system">')
    s.append('    <hardware><plugin>mock_components/GenericSystem</plugin></hardware>')
    for n, *_ in js:
        s.append(f'    <joint name="{n}"><command_interface name="position"/>'
                 '<state_interface name="position"><param name="initial_value">0.0</param></state_interface>'
                 '<state_interface name="velocity"/></joint>')
    s.append('  </ros2_control>')
    s.append('</robot>')
    return "\n".join(s) + "\n"


def yaml_str(text):
    # A double-quoted YAML scalar; the URDF has no backslashes or double quotes inside attributes
    # other than the ones escaped here.
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--rate", type=int, default=250)
    a = ap.parse_args()
    out = os.path.abspath(a.out)
    os.makedirs(out, exist_ok=True)
    u = urdf(a.rate)
    with open(f"{out}/g1.urdf", "w") as f:
        f.write(u)
    jl = "[" + ", ".join(joints()) + "]"
    with open(f"{out}/controllers.yaml", "w") as f:
        f.write(f"""controller_manager:
  ros__parameters:
    update_rate: {a.rate}
    robot_description: {yaml_str(u)}
    joint_state_broadcaster:
      type: joint_state_broadcaster/JointStateBroadcaster
    forward_position_controller:
      type: forward_command_controller/ForwardCommandController
forward_position_controller:
  ros__parameters:
    joints: {jl}
    interface_name: position
""")
    with open(f"{out}/rsp.yaml", "w") as f:
        f.write(f"/**:\n  ros__parameters:\n    publish_frequency: 100.0\n    robot_description: {yaml_str(u)}\n")
    with open(f"{out}/humanoid.spec", "w") as f:
        f.write(f"""# Real ROS 2 humanoid stack (stock Humble packages, mock ros2_control hardware), generated by
# eval/heal/humanoid/make_stack.py. Frozen before any humanoid episode ran.
#   controller_manager -> /joint_states ({a.rate} Hz) -> rsp -> /tf (83 Hz: publish_frequency 100 is
#   throttled inside the 250 Hz joint_states callback, so it fires every 3rd message, 12 ms)
# The remap on controller_manager is node-targeted: a bare __node:= remap would also rename
# the controller nodes inside the same process and they would lose their parameters.
#   camera (cam2image) -> /image (30 Hz), falls back to camera_backup (15 Hz)
healer startup_grace_s=3 verify_s=5

node controller_manager
out controller_manager /joint_states {a.rate}
exec controller_manager /opt/ros/humble/lib/controller_manager/ros2_control_node --ros-args --params-file {out}/controllers.yaml -r controller_manager:__node:=controller_manager
then controller_manager @controller_manager/spawner joint_state_broadcaster forward_position_controller -c /controller_manager

node rsp
in rsp /joint_states
out rsp /tf 83
exec rsp /opt/ros/humble/lib/robot_state_publisher/robot_state_publisher --ros-args --params-file {out}/rsp.yaml

node camera fallback=camera_backup
out camera /image 30
exec camera @image_tools/cam2image --ros-args -p burger_mode:=true -p frequency:=30.0

node camera_backup autostart=0
out camera_backup /image 15
exec camera_backup @image_tools/cam2image --ros-args -p burger_mode:=true -p frequency:=15.0
""")
    print(out)


if __name__ == "__main__":
    main()
